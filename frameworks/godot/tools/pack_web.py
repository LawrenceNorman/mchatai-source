def frame(title: str, blurb: str) -> str:
    esc = lambda s: (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;"))
    return FRAME % {"title": esc(title or "Play"), "blurb": esc(blurb), "blurb_hidden": "" if blurb else " hidden",
                    "icon_full": ICON_FULL, "icon_full_js": json.dumps(ICON_FULL), "icon_small_js": json.dumps(ICON_SMALL)}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("export_dir")
    ap.add_argument("out_dir")
    ap.add_argument("--engine", default="4.7.2")
    ap.add_argument("--title", default="")
    ap.add_argument("--blurb", default="", help="the premise in a sentence or two, shown on the start screen")
    a = ap.parse_args()
    src, out, v = Path(a.export_dir), Path(a.out_dir), a.engine
    page = (src / "index.html").read_text()
    m = re.search(r'const GODOT_CONFIG = (\{.*?\});', page)
    if not m:
        sys.exit("no GODOT_CONFIG in the export's index.html")
    cfg = json.loads(m.group(1))
    exe = cfg.get("executable", "index")
    need = {"js": src / f"{exe}.js", "wasm": src / f"{exe}.wasm", "pck": src / f"{exe}.pck",
            "worklet": src / f"{exe}.audio.worklet.js", "positionWorklet": src / f"{exe}.audio.position.worklet.js"}
    missing = [str(p) for p in need.values() if not p.exists()]
    if missing:
        sys.exit("the export is missing: " + ", ".join(missing))

    (out / "libs").mkdir(parents=True, exist_ok=True)
    engine_js = need["js"].read_bytes()
    (out / "libs" / f"godot-{v}.js").write_bytes(engine_js)
    (out / "libs" / f"godot-{v}-files.js").write_text(engine_files_js(
        v, need["wasm"].read_bytes(), need["worklet"].read_text(), need["positionWorklet"].read_text()))

    # The page: Godot's own, with the page frame, the engine from libs/, the loader, and the pack inside.
    title = a.title or (re.search(r"<title>(.*?)</title>", page, flags=re.S) or [None, ""])[1].strip()
    page, n = re.subn(re.escape(f'<script src="{exe}.js"></script>'),
                      lambda _: frame(title, a.blurb.strip()) +
                      f'\t\t<script src="./libs/godot-{v}.js"></script>\n'
                      f'\t\t<script src="./libs/godot-{v}-files.js"></script>\n' + LOADER % {"version": json.dumps(v)},
                      page, count=1)
    if n != 1:
        sys.exit(f'no <script src="{exe}.js"> in the export\'s index.html')
    page, n = re.subn(r"(\s*</head>)", lambda m: "\n" + FRAME_CSS + m.group(1), page, count=1)
    if n != 1:
        sys.exit("no </head> in the export's index.html")
    # The frame learns when the game quits through the engine's onExit hook.
    page, n = re.subn(r"new Engine\(GODOT_CONFIG\)",
                      "new Engine(window.MChatAIGodotFrame ? window.MChatAIGodotFrame.config(GODOT_CONFIG) : GODOT_CONFIG)",
                      page, count=1)
    if n != 1:
        sys.exit("no `new Engine(GODOT_CONFIG)` in the export's index.html")
    # The fetch->XHR shim is not needed: nothing is fetched from disk any more.
    page = re.sub(r"<script>\s*/\* mChatAI file:// shim.*?</script>\s*", "", page, flags=re.S)
    # Icons and the splash picture: small files, inlined so the page has no loose references.
    for f in sorted(src.glob(f"{exe}*.png")):
        uri = "data:image/png;base64," + base64.b64encode(f.read_bytes()).decode("ascii")
        page = page.replace(f'"{f.name}"', f'"{uri}"')
    page = re.sub(r'\s*<link[^>]+rel="manifest"[^>]*>', "", page)
    if a.title:
        page = re.sub(r"<title>.*?</title>", f"<title>{a.title}</title>", page, flags=re.S)
    pck = b64gz(need["pck"].read_bytes())
    # At the top of the body: Godot asks for its pack as soon as the page's start script runs.
    page, n = re.subn(r"(<body[^>]*>)", lambda m: m.group(1) + f'\n<script type="application/octet-stream" id="mchatai-godot-pck">{pck}</script>', page, count=1)
    if n != 1:
        sys.exit("no <body> in the export's index.html")
    if len(page.encode()) > MAX_PAGE:
        sys.exit(f"the page would be {len(page.encode()) / 1e6:.1f} MB, over the Hub's 25 MB: make the game's pack "
                 f"smaller (lossy web textures, fewer or smaller pictures)")
    (out / "index.html").write_text(page)

    def sha(p: Path) -> str:
        return hashlib.sha256(p.read_bytes()).hexdigest()
    report = {"engine": v, "page": {"bytes": (out / "index.html").stat().st_size},
              "libs": {p.name: {"bytes": p.stat().st_size, "sha256": sha(p)} for p in sorted((out / "libs").iterdir())}}
    print(json.dumps(report, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
