#!/usr/bin/env python3
"""Turn a Godot web export into a mini-app: one index.html plus the shared engine in libs/.

  python3 pack_web.py <export-dir> <out-dir> [--engine 4.7.2] [--title "Alesia, 52 BC"]

A Godot web export is several files (index.html, index.js, index.wasm, index.pck, two audio worklets,
icons). mChatAI+ installs, versions and publishes a mini-app as ONE index.html whose ./libs/*.js
files are vendored at install (frameworks/_index/web-libs.json) and point at mchatai.com/v/lib/
once published (the retro-fps pattern). So this script writes:

  <out>/index.html                 the export's page, with the game's .pck inside it (gzip + base64)
                                   and a small loader that hands Godot its files from memory
  <out>/libs/godot-<v>.js          the engine's JavaScript (Godot's index.js, unchanged)
  <out>/libs/godot-<v>-files.js    the engine's wasm (gzip + base64) and its two audio worklets

The engine files are the same for every game on that Godot version, so a page shares one cached
copy once published. The loader answers Godot's fetch() of <executable>.wasm and of the main pack,
and its audioWorklet.addModule() of the two worklets, from memory: nothing is fetched from disk,
so the page runs from file:// in a WKWebView without the fetch->XHR shim.

Limits: the published page must stay under the Hub's 25 MB, so the pck (after gzip and base64)
must be under about 23 MB. The script refuses a bigger one and says so.

Standard library only.
"""
from __future__ import annotations

import argparse
import base64
import gzip
import hashlib
import json
import re
import sys
from pathlib import Path

MAX_PAGE = 25 * 1000 * 1000  # the Hub deploy's limit (web-api MAX_HTML_BYTES), with margin left below


def b64gz(data: bytes) -> str:
    return base64.b64encode(gzip.compress(data, 9, mtime=0)).decode("ascii")


def engine_files_js(v: str, wasm: bytes, worklet: str, position_worklet: str) -> str:
    """libs/godot-<v>-files.js: the same bytes from an export or from the template (tools/build_dist.py)."""
    files = {"wasm": b64gz(wasm), "worklet": worklet, "positionWorklet": position_worklet}
    return ("/* Godot " + v + " engine for mChatAI mini-apps: wasm (gzip+base64) and audio worklets. "
            "Generated by frameworks/godot/tools from the official single-threaded web template. */\n"
            "window.MChatAIGodotFiles = window.MChatAIGodotFiles || {};\n"
            f"window.MChatAIGodotFiles[{json.dumps(v)}] = " + json.dumps(files, sort_keys=True) + ";\n")


LOADER = r"""<script>
/* mChatAI Godot loader: answers the engine's requests for its files from memory (frameworks/godot). */
(function () {
  var V = %(version)s;
  var files = (window.MChatAIGodotFiles || {})[V];
  if (!files) { console.error('Godot engine files for ' + V + ' are missing (libs/godot-' + V + '-files.js)'); return; }
  function bytes(b64) {
    var s = atob(b64), n = s.length, a = new Uint8Array(n);
    for (var i = 0; i < n; i++) a[i] = s.charCodeAt(i);
    return a;
  }
  function gunzip(b64) {
    return new Response(new Blob([bytes(b64)]).stream().pipeThrough(new DecompressionStream('gzip'))).arrayBuffer();
  }
  // The pack sits at the end of the page, so it is looked up when Godot asks for it, not now.
  function pckNode() { return document.getElementById('mchatai-godot-pck'); }
  var memo = {};
  function body(kind) {
    if (!memo[kind]) memo[kind] = kind === 'wasm' ? gunzip(files.wasm) : gunzip(pckNode().textContent.trim());
    return memo[kind];
  }
  var realFetch = window.fetch.bind(window);
  window.fetch = function (input, init) {
    var url = typeof input === 'string' ? input : (input && input.url) || '';
    var name = url.split('?')[0].split('#')[0].split('/').pop();
    if (/\.wasm$/.test(name)) {
      return body('wasm').then(function (b) { return new Response(b, { headers: { 'Content-Type': 'application/wasm' } }); });
    }
    if (/\.pck$/.test(name) && pckNode()) {
      return body('pck').then(function (b) { return new Response(b, { headers: { 'Content-Type': 'application/octet-stream' } }); });
    }
    return realFetch(input, init);
  };
  if (window.AudioWorklet && AudioWorklet.prototype.addModule) {
    var realAdd = AudioWorklet.prototype.addModule;
    var blobs = {};
    AudioWorklet.prototype.addModule = function (url, opts) {
      var name = String(url).split('/').pop();
      var key = /position\.worklet\.js$/.test(name) ? 'positionWorklet' : (/worklet\.js$/.test(name) ? 'worklet' : null);
      if (key && files[key]) {
        // From disk (file://, an opaque origin) Chromium refuses a worklet module from blob:null, so use a
        // data: URL. Published on mchatai.com the page's CSP allows blob: scripts but not data: ones, so
        // use a blob: URL there.
        if (!blobs[key]) {
          blobs[key] = location.protocol === 'file:'
            ? 'data:text/javascript;base64,' + btoa(unescape(encodeURIComponent(files[key])))
            : URL.createObjectURL(new Blob([files[key]], { type: 'text/javascript' }));
        }
        return realAdd.call(this, blobs[key], opts);
      }
      return realAdd.call(this, url, opts);
    };
  }
})();
</script>
"""

