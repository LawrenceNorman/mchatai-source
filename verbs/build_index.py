#!/usr/bin/env python3
"""Compiles verbs/ios/*.json into the copy the chat fetches (Phase AV.0, 2026-11-09):
personas/_verbs.json (generated, never hand-edited) and the `verbs` list inside personas/_index.json,
bumping the index version to today's YYYY.MM.DD.n.

    python3 verbs/build_index.py            # write
    python3 verbs/build_index.py --check    # exit 1 when the compiled copy is stale
"""
import datetime, json, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import validate_verbs as v  # noqa: E402
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / 'sources'))
import validate_sources as sv  # noqa: E402


def next_version(current):
    today = datetime.date.today().strftime('%Y.%m.%d')
    if current and current.startswith(today):
        tail = current[len(today):]
        n = int(tail[1:]) if tail.startswith('.') and tail[1:].isdigit() else 0
        return f'{today}.{n + 1}'
    return f'{today}.1'


def main(argv):
    nouns, caps, verbs = v.load_catalog()
    found = v.problems(nouns, caps, verbs)
    if found:
        print('\n'.join(found)); return 1
    sources = sv.load()
    found = sv.problems(sources)
    if found:
        print('\n'.join(found)); return 1
    compiled_sources = sv.compiled(sources)
    styles = next((c.get('styles') or {} for c in caps['capabilities'] if c['id'] == 'text.summarize'), {})
    template = v.agent_template(caps)
    compiled = v.compiled_verbs(verbs)
    if '--check' in argv:
        found = v.compiled_problems(verbs, caps=caps)
        print('\n'.join(found) if found else 'compiled copy is current')
        return 1 if found else 0
    index_path = v.PERSONAS / '_index.json'
    index = json.loads(index_path.read_text())
    if index.get('verbs') == compiled and index.get('sources') == compiled_sources and index.get('textStyles') == styles \
            and index.get('agentTemplate') == template:
        print('compiled copy already current'); return 0
    index['verbs'] = compiled
    index['sources'] = compiled_sources
    index['textStyles'] = styles
    index['agentTemplate'] = template
    index['version'] = next_version(index.get('version'))
    index_path.write_text(json.dumps(index, indent=1, ensure_ascii=False) + '\n')
    out = {
        '_schema': 'mchatai-source/personas/_verbs.json — GENERATED by verbs/build_index.py from verbs/ios/*.json (Phase AV.0); edit the verb files, never this one. The same list rides inside personas/_index.json so one fetch serves the chat. Design: mchatai_macOS/docs/IOS_AGENT_SKILLS_PLAN.md.',
        '_generated': True,
        'version': index['version'],
        'verbs': compiled,
    }
    (v.PERSONAS.parent / 'sources' / '_index.json').write_text(json.dumps({
        '_schema': 'mchatai-source/sources/_index.json — GENERATED by verbs/build_index.py from sources/*.json (Phase AV.3); edit the pack files, never this one.',
        '_generated': True, 'version': index['version'], 'sources': compiled_sources}, indent=2, ensure_ascii=False) + '\n')
    (v.PERSONAS / '_verbs.json').write_text(json.dumps(out, indent=2, ensure_ascii=False) + '\n')
    print(f"wrote {len(compiled)} verbs; personas/_index.json version {index['version']}")
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
